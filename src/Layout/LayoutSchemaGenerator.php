<?php

declare(strict_types=1);

namespace App\Layout;

use Symfony\AI\Platform\StructuredOutput\ResponseFormatFactoryInterface;
use Symfony\Component\VarExporter\VarExporter;

/**
 * Builds the layout schema exactly as Symfony AI sends it to a model as `response_format`,
 * so the MCP tool can declare the same schema as a constant (LayoutSchema::DEFINITION).
 */
final readonly class LayoutSchemaGenerator
{
    public function __construct(
        private ResponseFormatFactoryInterface $responseFormatFactory,
    ) {
    }

    /**
     * @return array<string, mixed>
     */
    public function schema(): array
    {
        return $this->responseFormatFactory->create(Page::class)['json_schema']['schema'];
    }

    public function phpFile(): string
    {
        return <<<PHP
            <?php

            declare(strict_types=1);

            namespace App\\Layout;

            /**
             * The JSON Schema of Page, as Symfony AI builds it for structured output.
             *
             * Generated by `bin/console app:dump-layout-schema`: do not edit by hand.
             * LayoutSchemaTest fails when this constant and the classes drift apart.
             */
            final class LayoutSchema
            {
                public const array DEFINITION = {$this->export()};
            }

            PHP;
    }

    private function export(): string
    {
        $code = VarExporter::export($this->schema());

        return str_replace("\n", "\n    ", $code);
    }
}
